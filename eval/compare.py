import argparse
import glob
import json
import os

from app.evaluation import KS, QUESTION_SETS, RESULTS_DIR, format_cost, results_name
from app.indexing import ChunkSettings

CONFIGS = [["dense"], ["bm25"], ["dense", "bm25"]]
OUTPUT = os.path.join(RESULTS_DIR, "comparison.md")


def load(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def find_files(corpus, settings, config):
    base = f"{RESULTS_DIR}/{results_name(corpus, settings, config)}"
    answers = sorted(path.replace(os.sep, "/") for path in glob.glob(f"{base}-answers-*.json"))
    return (f"{base}.json" if os.path.exists(f"{base}.json") else None), (answers[-1] if answers else None)


def table(header, rows):
    return [f"| {' | '.join(header)} |", f"|{'---|' * len(header)}", *(f"| {' | '.join(map(str, row))} |" for row in rows)]


def type_rows(corpus, config, report):
    """One row per question type, plus overall. Types without retrieval stats (not_in_corpus) get n and dashes."""
    summary = report["summary"]
    counts = {}
    for row in report["results"]:
        counts[row["type"]] = counts.get(row["type"], 0) + 1
    rows = []
    for kind in ["overall", *counts]:
        stats = summary["overall"] if kind == "overall" else summary["by_type"].get(kind)
        values = ([f"{stats[f'hit@{k}']:.2f}" for k in KS] + [f"{stats[f'recall@{k}']:.2f}" for k in KS]
                  if stats else ["—"] * (2 * len(KS)))
        rows.append([corpus, config, f"**{kind}**" if kind == "overall" else kind,
                     stats["questions"] if stats else counts[kind], *values])
    return rows


def recall_at_5(retrieval):
    # Saved files have string keys ("5"), reports still in memory have int keys.
    return retrieval["recall"].get("5", retrieval["recall"].get(5))


def mark(base, other):
    """▲ or ▼ when the evidence found in the top 5 (hit@5 / recall@5) went up or down against the base config."""
    if base is None or other is None or recall_at_5(other) == recall_at_5(base):
        return ""
    return " ▲" if recall_at_5(other) > recall_at_5(base) else " ▼"


def question_cell(retrieval, base):
    ranks = "/".join(str(rank) if rank else "—" for rank in retrieval["evidence_ranks"])
    return f"{ranks} · R@5 {recall_at_5(retrieval):.2f}{mark(base, retrieval)}"


def compare(settings):
    found = {corpus: {"+".join(config): find_files(corpus, settings, config) for config in CONFIGS}
             for corpus in QUESTION_SETS}
    reports = {corpus: {name: load(files[0]) for name, files in configs.items() if files[0]}
               for corpus, configs in found.items()}

    lines = ["# Retrieval comparison", "", f"Chunks {settings.chunk_size} / {settings.overlap_percent} %. "
             "Generated by `python -m eval.compare` from:", ""]
    for corpus, configs in found.items():
        for name, (retrieval, answers) in configs.items():
            lines.append(f"- {corpus}, {name}: `{retrieval or 'missing'}`" + (f", answers `{answers}`" if answers else ""))

    lines += ["", "## Hit and recall per question type", "", *table(
        ["corpus", "config", "type", "n", *(f"hit@{k}" for k in KS), *(f"recall@{k}" for k in KS)],
        [row for corpus, configs in reports.items() for name, report in configs.items()
         for row in type_rows(corpus, name, report)])]

    cost_rows = []
    for corpus, configs in found.items():
        for name, (retrieval, answers) in configs.items():
            retrieval_cost = load(retrieval)["summary"].get("cost") if retrieval else None
            answer_cost = load(answers)["summary"].get("cost") if answers else None
            cost_rows.append([corpus, name,
                              format_cost({"retrieval": retrieval_cost["retrieval"], "answer": None}) if retrieval_cost else "—",
                              format_cost({"retrieval": None, "answer": answer_cost["answer"]})
                              if answer_cost and answer_cost["answer"] else "—"])
    lines += ["", "## Cost per question", "", *table(["corpus", "config", "retrieval (top 10)", "answer (top-k + LLM)"],
                                                     cost_rows)]

    for corpus, configs in reports.items():
        names = list(configs)
        base = configs[names[0]] if names else None
        by_id = {name: {row["id"]: row for row in report["results"]} for name, report in configs.items()}
        rows = []
        for row in base["results"] if base else []:
            if "retrieval" not in row:
                continue
            base_retrieval = row["retrieval"]
            rows.append([row["id"], row["type"], *(
                question_cell(by_id[name][row["id"]]["retrieval"], None if name == names[0] else base_retrieval)
                if row["id"] in by_id[name] else "—" for name in names)])
        lines += ["", f"## Per question: {corpus}", "",
                  f"Evidence ranks in the top 10 (one per evidence item) and recall@5. ▲ / ▼: recall@5 against {names[0]}.",
                  "", *table(["id", "type", *names], rows)]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description="Compare the saved evaluation results of every retriever configuration.")
    parser.add_argument("--chunk-size", type=int, default=800)
    parser.add_argument("--overlap", type=int, default=10)
    args = parser.parse_args()

    text = compare(ChunkSettings(chunk_size=args.chunk_size, overlap_percent=args.overlap))
    print(text)
    with open(OUTPUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"Saved {OUTPUT}")


if __name__ == "__main__":
    main()
